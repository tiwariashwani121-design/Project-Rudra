/**
 * Creates a smart translator proxy that supports both property access t.key and function call t('key')
 * and falls back seamlessly to English and key name if any translation is missing.
 */
export function getTranslator(lang) {
  const current = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const fallback = TRANSLATIONS.en;

  const fn = (key, defaultText) => {
    return current[key] || fallback[key] || defaultText || key;
  };

  return new Proxy(fn, {
    get(target, prop) {
      if (typeof prop === 'string') {
        if (prop in current) return current[prop];
        if (prop in fallback) return fallback[prop];
      }
      return target[prop];
    }
  });
}
